          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT fk_student_groups_leader
            FOREIGN KEY (leader_student_id) REFERENCES students(id) ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_student_groups_import_batch'
          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT fk_student_groups_import_batch
            FOREIGN KEY (import_batch_id) REFERENCES import_batches(id) ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_student_groups_status'
          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT chk_student_groups_status
            CHECK (status IN ('ACTIVE', 'INACTIVE'));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_student_groups_required_gpa'
          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT chk_student_groups_required_gpa
            CHECK (required_gpa >= 0.00 AND required_gpa <= 4.00);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_student_groups_target_grade'
          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT chk_student_groups_target_grade
            CHECK (target_grade >= 0.0 AND target_grade <= 10.0);
    END IF;

    WITH duplicated_groups AS (
        SELECT id,
               ROW_NUMBER() OVER (
                   PARTITION BY term, course_code, group_no
                   ORDER BY id
               ) AS duplicate_rank
        FROM student_groups
    )
    UPDATE student_groups sg
    SET group_no = CONCAT('DUP-', sg.id)
    FROM duplicated_groups dg
    WHERE sg.id = dg.id
      AND dg.duplicate_rank > 1;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_student_groups_term_course_group_no'
          AND conrelid = 'student_groups'::regclass
    ) THEN
        ALTER TABLE student_groups
            ADD CONSTRAINT uq_student_groups_term_course_group_no
            UNIQUE (term, course_code, group_no);
    END IF;
END;
$$;

