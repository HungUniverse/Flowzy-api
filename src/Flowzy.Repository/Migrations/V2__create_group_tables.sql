-- Enforce membership constraint: A student can belong to only one group per term + course_code
CREATE OR REPLACE FUNCTION check_student_group_membership_limit()
RETURNS TRIGGER AS $$
DECLARE
    v_term VARCHAR(30);
    v_course_code VARCHAR(30);
BEGIN
    SELECT term, course_code INTO v_term, v_course_code
    FROM student_groups
    WHERE id = NEW.group_id;

    IF EXISTS (
        SELECT 1 
        FROM student_group_members sgm
        JOIN student_groups sg ON sgm.group_id = sg.id
        WHERE sgm.student_id = NEW.student_id
          AND sg.term = v_term
          AND sg.course_code = v_course_code
          AND sgm.id <> COALESCE(NEW.id, -1)
    ) THEN
        RAISE EXCEPTION 'Student is already a member of a group in the same term and course';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trigger_check_student_group_membership'
          AND tgrelid = 'student_group_members'::regclass
    ) THEN
        CREATE TRIGGER trigger_check_student_group_membership
            BEFORE INSERT OR UPDATE ON student_group_members
            FOR EACH ROW
            EXECUTE FUNCTION check_student_group_membership_limit();
    END IF;
END;
$$;

-- Trigger to prevent term/course updates from breaking membership uniqueness
CREATE OR REPLACE FUNCTION check_group_term_course_update()
RETURNS TRIGGER AS $$
BEGIN
    IF (OLD.term <> NEW.term OR OLD.course_code <> NEW.course_code) THEN
        IF EXISTS (
            SELECT 1 FROM student_group_members sgm1
            JOIN student_group_members sgm2 ON sgm1.student_id = sgm2.student_id
            WHERE sgm1.group_id = NEW.id
              AND sgm2.group_id <> NEW.id
              AND sgm2.group_id IN (
                  SELECT id FROM student_groups 
                  WHERE term = NEW.term AND course_code = NEW.course_code
              )
        ) THEN
            RAISE EXCEPTION 'Cannot update group term/course because it would violate student membership uniqueness constraint';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trigger_check_group_term_course_update'
          AND tgrelid = 'student_groups'::regclass
    ) THEN
        CREATE TRIGGER trigger_check_group_term_course_update
            BEFORE UPDATE ON student_groups
            FOR EACH ROW
            EXECUTE FUNCTION check_group_term_course_update();
    END IF;
END;
$$;
