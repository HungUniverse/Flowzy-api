CREATE TABLE IF NOT EXISTS import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(30) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    total_rows INTEGER NOT NULL,
    success_rows INTEGER NOT NULL,
    failed_rows INTEGER NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    created_by BIGINT,
    CONSTRAINT fk_import_batches_creator FOREIGN KEY (created_by) REFERENCES accounts(id) ON DELETE SET NULL,
    CONSTRAINT chk_import_batches_target CHECK (target_type IN ('STUDENT', 'MENTOR')),
    CONSTRAINT chk_import_batches_file_type CHECK (file_type IN ('CSV', 'XLSX')),
    CONSTRAINT chk_import_batches_status CHECK (status IN ('COMPLETED', 'FAILED')),
    CONSTRAINT chk_import_batches_total_rows CHECK (total_rows >= 0),
    CONSTRAINT chk_import_batches_success_rows CHECK (success_rows >= 0),
    CONSTRAINT chk_import_batches_failed_rows CHECK (failed_rows >= 0),
